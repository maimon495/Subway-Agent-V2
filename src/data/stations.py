# Build lookup maps
_station_by_id: dict[str, Station] = {s.id: s for s in STATIONS}

_station_by_gtfs_id: dict[str, Station] = {}
for station in STATIONS:
    base_id = station.gtfs_stop_ids["N"].rstrip("N")
    _station_by_gtfs_id[base_id] = station
    _station_by_gtfs_id[station.gtfs_stop_ids["N"]] = station
    _station_by_gtfs_id[station.gtfs_stop_ids["S"]] = station

_stations_by_line: dict[str, list[Station]] = {}
for station in STATIONS:
    for line in station.lines:
        if line not in _stations_by_line:
            _stations_by_line[line] = []
        _stations_by_line[line].append(station)


def get_station_by_id(station_id: str) -> Optional[Station]:
    """Get a station by its internal ID."""
    return _station_by_id.get(station_id)


def get_station_by_gtfs_id(gtfs_id: str) -> Optional[Station]:
    """Get a station by its GTFS stop ID."""
    base_id = gtfs_id.rstrip("NS")
    return _station_by_gtfs_id.get(base_id) or _station_by_gtfs_id.get(gtfs_id)


def get_stations_for_line(line_id: str) -> list[Station]:
    """Get all stations on a given line."""
    return _stations_by_line.get(line_id.upper(), [])


import re

def _normalize_query(query: str) -> str:
    """Normalize query by removing ordinal suffixes and standardizing format."""
    normalized = query.lower().strip()
    # Convert ordinals: 1st->1, 2nd->2, 3rd->3, 4th->4, etc.
    normalized = re.sub(r'(\d+)(st|nd|rd|th)\b', r'\1', normalized)
    # Normalize street/avenue abbreviations
    normalized = re.sub(r'\bstreet\b', 'st', normalized)
    normalized = re.sub(r'\bavenue\b', 'av', normalized)
    return normalized


def find_station_by_name(query: str) -> Optional[Station]:
    """Find a station by name or alias.

    Search priority:
    1. Exact ID match
    2. Exact name match (case-insensitive)
    3. Exact alias match
    4. Partial match - scored by relevance (more lines = higher priority)
    """
    normalized = _normalize_query(query)

    # Direct ID match
    if normalized in _station_by_id:
        return _station_by_id[normalized]

    # Exact name match
    for station in STATIONS:
        if station.name.lower() == normalized:
            return station

    # Alias match
    for station in STATIONS:
        if any(alias.lower() == normalized for alias in station.aliases):
            return station

    # Partial matches - collect all and score them
    partial_matches: list[tuple[int, Station]] = []

    for station in STATIONS:
        name_lower = station.name.lower()
        # Check if query is in station name
        if normalized in name_lower:
            # Score: number of lines (prioritize major hubs)
            # Bonus for name starting with query
            score = len(station.lines) * 10
            if name_lower.startswith(normalized):
                score += 100
            partial_matches.append((score, station))
            continue

        # Check if query is in any alias
        for alias in station.aliases:
            if normalized in alias.lower():
                score = len(station.lines) * 10
                if alias.lower().startswith(normalized):
                    score += 50
                partial_matches.append((score, station))
                break

    if partial_matches:
        # Return highest scoring match
        partial_matches.sort(key=lambda x: x[0], reverse=True)
        return partial_matches[0][1]

    return None


def find_stations_by_name(query: str, limit: int = 5) -> list[Station]:
    """Find stations matching a query, returning up to limit results sorted by relevance."""
    normalized = _normalize_query(query)
    scored_results: list[tuple[int, Station]] = []
    seen: set[str] = set()

    for station in STATIONS:
        if station.id in seen:
            continue

        score = 0
        name_lower = station.name.lower()

        # Exact matches get highest score
        if name_lower == normalized:
            score = 1000
        elif any(a.lower() == normalized for a in station.aliases):
            score = 900

        # Partial matches
        elif normalized in name_lower:
            score = len(station.lines) * 10
            if name_lower.startswith(normalized):
                score += 100
        elif any(normalized in a.lower() for a in station.aliases):
            score = len(station.lines) * 10
            if any(a.lower().startswith(normalized) for a in station.aliases):
                score += 50

        if score > 0:
            scored_results.append((score, station))
            seen.add(station.id)

    # Sort by score descending
    scored_results.sort(key=lambda x: x[0], reverse=True)

    return [station for _, station in scored_results[:limit]]

